    import math

    class GeometricShape:
        """
        Базовый класс для геометрических фигур.
        """

        def __init__(self, colour: str) -> None:
            """
            Конструктор класса ГеометрическаяФигура.

            Аргументы:
                colour (str): Цвет фигуры.
            Методы:
        square() -> float: Возвращает площадь фигуры (по умолчанию 0).
        perimeter() -> float: Возвращает периметр фигуры (по умолчанию 0).
        __str__() -> str: Возвращает строковое представление фигуры.
        __repr__() -> str: Возвращает строковое представление объекта для отладки.
            """
            self.colour = colour  # Инкапсуляция цвета, чтобы предотвратить случайное изменение напрямую

        def square(self) -> float:
            """
            Возвращает площадь фигуры.

            Возвращает:
                float: Площадь фигуры (по умолчанию 0).  Для конкретных фигур метод должен быть переопределен.
            """
            return 0.0

        def perimeter(self) -> float:
            """
            Возвращает периметр фигуры.

            Возвращает:
                float: Периметр фигуры (по умолчанию 0). Для конкретных фигур метод должен быть переопределен.
            """
            return 0.0

        def __str__(self) -> str:
            """
            Возвращает строковое представление фигуры.

            Возвращает:
                str: Строковое представление фигуры.
            """
            return f"GeometricShape: colour = {self.colour}"

        def __repr__(self) -> str:
            """
            Возвращает строковое представление объекта для отладки.

            Возвращает:
                str: Строковое представление объекта для отладки.
            """
            return f"GeometricShape(colour='{self.colour}')"


    class circle(GeometricShape):
        """
        Класс для представления круга.

        Наследует от класса GeometricShape.

        Атрибуты:
            radius (float): Радиус круга.

        Методы:
            square() -> float: Возвращает площадь круга. Переопределен для вычисления площади круга.
            perimeter() -> float: Возвращает длину окружности (периметр) круга. Переопределен.
            __str__() -> str: Возвращает строковое представление круга.Переопределен для включения информации о радиусе.
            __repr__() -> str: Возвращает строковое представление объекта для отладки.
        """

        def __init__(self, colour: str, radius: float) -> None:
            """
            Конструктор класса Круг.

            Аргументы:
                colour (str): Цвет круга.
                radius (float): Радиус круга.
            """
            super().__init__(colour)
            self.radius = radius

        def square(self) -> float:
            """
            Переопределенный метод для вычисления площади круга.

            Причина перегрузки: Базовый класс возвращает 0, а для круга нужна конкретная формула.

            Возвращает:
                float: Площадь круга.
            """
            return math.pi * self.radius ** 2

        def perimeter(self) -> float:
            """
            Переопределенный метод для вычисления периметра (длины окружности) круга.

            Причина перегрузки: Базовый класс возвращает 0, а для круга нужна конкретная формула.

            Возвращает:
                float: Периметр круга.
            """
            return 2 * math.pi * self.radius

        def __str__(self) -> str:
            """
            Переопределенный метод для возвращения строкового представления круга.

            Причина перегрузки: Добавление информации о радиусе.

            Возвращает:
                str: Строковое представление круга.
            """
            return f"circle: colour = {self.colour}, radius = {self.radius}"

        def __repr__(self) -> str:
            """
            Переопределенный метод для возвращения строкового представления объекта для отладки.

            Возвращает:
                str: Строковое представление объекта для отладки.
            """
            return f"circle(colour='{self.colour}', radius={self.radius})"
